@Injectable({ providedIn: 'root' })
export class I18nService {
  public readonly language = signal<AppLanguage>(this.getInitialLanguage());

  constructor() {
    this.applyDocumentLanguage(this.language());
  }

  toggleLanguage(): void {
    this.setLanguage(this.language() === 'en' ? 'fr' : 'en');
  }

  apiLanguageQuery(separator: '?' | '&' = '?'): string {
    return `${separator}language=${encodeURIComponent(this.language())}`;
  }

  setLanguage(language: AppLanguage): void {
    this.language.set(language);
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('app_language', language);
    }
    this.applyDocumentLanguage(language);
  }

  t(key: string, params: Record<string, string | number | null | undefined> = {}): string {
    const lang = this.language();
    let text = dictionary[lang][key] || dictionary.en[key] || key;
    Object.entries(params).forEach(([name, value]) => {
      text = text.replaceAll(`{{${name}}}`, String(value ?? ''));
    });
    return text;
  }

  private getInitialLanguage(): AppLanguage {
    if (typeof localStorage === 'undefined') {
      return 'en';
    }
    const saved = localStorage.getItem('app_language');
    return saved === 'fr' || saved === 'en' ? saved : 'en';
  }

  private applyDocumentLanguage(language: AppLanguage): void {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language;
    }
  }
}
